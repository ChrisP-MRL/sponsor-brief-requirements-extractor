#!/usr/bin/env python3
"""
Requirements Extractor (functional and non-functional)

Reads a formatted requirements text file, extracts solution requirements using
pattern matching, and writes them into a Requirements Specification workbook with
one worksheet per BABOK solution-requirement type:

  Functional Requirements     - capabilities the solution must have, in terms of
                                behaviour and the information it will manage
  Non-Functional Requirements - conditions under which the solution must remain
                                effective, or qualities it must have, each with a
                                measurable success measure

Routing between the two sheets is structural, never inferred from keywords: a
requirement is non-functional only if it sits under `MODULE: NON-FUNCTIONAL` or
under a section heading tagged `[NFR]`. Keyword inference would misfile security
and integration behaviour, which BABOK treats as functional, as quality
attributes. A keyword scan still runs, but only to advise the analyst which
functional requirements look like they belong on the other sheet.

The workbook is generated by frs_template.py rather than copied from a binary
.xlsx template, so this skill is self-contained - openpyxl is the only dependency.
"""

import sys
import re
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Tuple, Optional
from openpyxl.utils import get_column_letter

# Import the workbook builder from this script's own directory, so the script
# runs correctly from any working directory
sys.path.insert(0, str(Path(__file__).resolve().parent))
from frs_template import (create_workbook, style_requirement_row,
                          FUNCTIONAL_SHEET, NON_FUNCTIONAL_SHEET, NFR_CATEGORIES)


class FunctionalRequirementExtractor:
    # Headings the source document uses to group its requirements.
    # "MODULE: x" becomes CATEGORY; a lettered, markdown or ALL CAPS heading becomes SUB-CATEGORY.
    MODULE_RE = re.compile(r'^MODULE\s*:\s*(.+?)\s*$', re.MULTILINE)
    SECTION_RE = re.compile(r'^(?:[A-Z]\.|#{1,6})\s+(.+?)\s*$', re.MULTILINE)
    CAPS_HEADING_RE = re.compile(r"^([A-Z][A-Z0-9 &/'\-,()\[\]]{2,59})$", re.MULTILINE)

    # Marks a module or section as holding non-functional requirements
    NFR_MODULE_RE = re.compile(r'non[\s\-]?functional', re.IGNORECASE)
    NFR_TAG_RE = re.compile(r'\[\s*NFR\s*\]', re.IGNORECASE)

    # Attribute lines that qualify the requirement above them rather than
    # standing as requirements of their own
    ATTRIBUTE_RE = re.compile(
        r'^\s*(measure|success measure|target|sub-?category|category)\s*:\s*(.+?)\s*$',
        re.IGNORECASE)

    # Words left lowercase when an ALL CAPS heading is converted to title case
    SMALL_WORDS = {'a', 'an', 'and', 'as', 'at', 'by', 'for', 'from', 'in',
                   'of', 'on', 'or', 'the', 'to', 'vs', 'with'}

    # Filler words ignored when testing whether a sub-category restates its category
    FILLER_WORDS = {'general', 'requirement', 'requirements', 'system', 'management',
                    'control', 'controls', 'interface', 'analytics', 'story', 'stories'}

    # Acronyms preserved verbatim when an ALL CAPS heading is converted to title case
    ACRONYMS = {'PPE', 'SMS', 'API', 'UI', 'UX', 'CRM', 'FRS', 'NFR', 'SLA', 'IT',
                'HR', 'ERP', 'RTO', 'RPO', 'WCAG', 'SSO'}

    # Canonical BABOK s10.30 category order, taken from the workbook builder so the
    # two files cannot drift apart
    NFR_CATEGORY_ORDER = [name for name, _ in NFR_CATEGORIES]

    # Section-heading vocabulary mapped onto the canonical categories. A heading is
    # matched on any of these tokens so analysts can write the business's own words.
    NFR_CATEGORY_ALIASES = {
        'Availability': ['availability', 'available', 'uptime', 'operating hours'],
        'Compatibility': ['compatibility', 'integration', 'interoperability',
                          'interfaces', 'data standards'],
        'Compliance': ['compliance', 'regulatory', 'legislative', 'privacy',
                       'audit', 'records retention'],
        'Business Continuity': ['continuity', 'disaster', 'recovery', 'fallback',
                                'resilience of the business', 'backup'],
        'Functionality': ['functionality', 'accuracy', 'suitability'],
        'Maintainability': ['maintainability', 'supportability', 'configurability',
                            'extensibility'],
        'Operability': ['operability', 'operations', 'monitoring', 'supportability'],
        'Performance Efficiency': ['performance', 'response time', 'responsiveness',
                                   'throughput', 'efficiency', 'latency'],
        'Portability': ['portability', 'deployment', 'environments'],
        'Reliability': ['reliability', 'resilience', 'stability', 'error rate'],
        'Scalability': ['scalability', 'scale', 'capacity', 'volume', 'growth'],
        'Security': ['security', 'access control', 'authorisation', 'authorization',
                     'encryption', 'authentication'],
        'Usability': ['usability', 'accessibility', 'user experience', 'training',
                      'ease of use', 'learnability'],
    }

    # Phrasing that suggests a quality threshold rather than a behaviour. Used only
    # to advise the analyst - never to move a requirement between sheets.
    #
    # Kept deliberately narrow. Loose stems like 'availab' or 'recover' fire on
    # ordinary functional language ("present stock availability", "cost recovery")
    # and an advisory that cries wolf gets ignored.
    NFR_SIGNALS = [
        'response time', 'peak volume', 'peak induction', 'concurrent', 'uptime',
        'system availability', 'scalab', 'throughput', 'degrade', 'outage',
        'remain usable', 'remain effective', 'recovery time', 'per second',
        'downtime', 'manual fallback', 'without delaying',
    ]

    def __init__(self, output_dir: str = "requirements"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        # Populated during extraction and reported back to the analyst
        self.warnings: List[str] = []
        self.advisories: List[str] = []

    def _titlecase_heading(self, heading: str) -> str:
        """Convert an ALL CAPS heading to Title Case, leaving known acronyms intact."""
        words = []
        for i, word in enumerate(heading.strip().split()):
            stripped = word.strip('()[],')
            if stripped.upper() in self.ACRONYMS:
                words.append(word.replace(stripped, stripped.upper()))
            elif i > 0 and word.lower() in self.SMALL_WORDS:
                words.append(word.lower())
            else:
                words.append(word.capitalize())
        return ' '.join(words)

    def _build_heading_map(self, text: str) -> List[Tuple[int, str, str, bool]]:
        """
        Build an ordered list of (offset, module, section, is_non_functional).

        Lets CATEGORY and SUB-CATEGORY be driven by the document's own structure
        rather than by restating a keyword category twice, and lets the document
        state which sheet a block of requirements belongs on.
        """
        headings = []

        for match in self.MODULE_RE.finditer(text):
            headings.append((match.start(), 'module', match.group(1)))

        for match in self.SECTION_RE.finditer(text):
            headings.append((match.start(), 'section', match.group(1)))

        for match in self.CAPS_HEADING_RE.finditer(text):
            heading = match.group(1).strip()
            # Skip headings that are really sentences or metadata lines
            if heading.endswith(('.', ':')) or len(heading.split()) > 8:
                continue
            headings.append((match.start(), 'section', heading))

        headings.sort(key=lambda h: h[0])

        # Walk the document, carrying the most recent module and section forward.
        # The non-functional flag is sticky per module and can also be set on a
        # single section with a [NFR] tag.
        resolved = []
        module, section = '', ''
        module_is_nfr, section_is_nfr = False, False
        for offset, kind, raw in headings:
            tagged = bool(self.NFR_TAG_RE.search(raw))
            clean = self._titlecase_heading(self.NFR_TAG_RE.sub('', raw).strip(' -:'))
            if kind == 'module':
                module_is_nfr = tagged or bool(self.NFR_MODULE_RE.search(raw))
                module, section, section_is_nfr = clean, '', False
            else:
                section, section_is_nfr = clean, tagged
            resolved.append((offset, module, section,
                             module_is_nfr or section_is_nfr))

        return resolved

    def _heading_at(self, heading_map, offset: int) -> Tuple[str, str, bool]:
        """Return the headings and sheet routing in force at a character offset."""
        module, section, is_nfr = '', '', False
        for h_offset, h_module, h_section, h_is_nfr in heading_map:
            if h_offset > offset:
                break
            module, section, is_nfr = h_module, h_section, h_is_nfr
        return module, section, is_nfr

    def _line_index(self, text: str) -> List[Tuple[int, str]]:
        """Return (start offset, raw line) for every line, for attribute lookups."""
        index, offset = [], 0
        for line in text.split('\n'):
            index.append((offset, line))
            offset += len(line) + 1  # +1 for the newline consumed by split
        return index

    def _attributes_after(self, line_index, offset: int) -> Dict[str, str]:
        """
        Collect the `Measure:` / `Sub-category:` lines attached to a requirement.

        Attribute lines sit directly beneath the requirement they qualify. Reading
        stops at the first line that is not an attribute, so a blank line or the
        next requirement ends the block.
        """
        attributes: Dict[str, str] = {}
        started = False
        for line_offset, line in line_index:
            if not started:
                if line_offset <= offset < line_offset + len(line) + 1:
                    started = True
                continue
            match = self.ATTRIBUTE_RE.match(line)
            if not match:
                break
            key = match.group(1).lower().replace('subcategory', 'sub-category')
            if key in ('success measure', 'target'):
                key = 'measure'
            attributes[key] = match.group(2).strip()
        return attributes

    def _is_attribute_line(self, line_index, offset: int) -> bool:
        """True if the offset falls on an attribute line rather than a requirement."""
        for line_offset, line in line_index:
            if line_offset <= offset < line_offset + len(line) + 1:
                return bool(self.ATTRIBUTE_RE.match(line))
        return False

    def extract_requirements_from_text(self, text: str) -> List[Dict[str, str]]:
        """
        Extract solution requirements from text content.
        Looks for patterns that indicate requirements:
        - Numbered lists (1., 2., etc.)
        - "Must", "Should", "Shall" statements
        - User story format ("As a... I want... So that...")
        - Feature descriptions

        Each requirement carries the headings in force where it was found, the
        sheet it routes to, and any success measure stated beneath it.
        """
        requirements = []
        heading_map = self._build_heading_map(text)
        line_index = self._line_index(text)

        def add(req_text: str, offset: int, category: str, priority: str = None):
            # An attribute line qualifies the requirement above it; it is not one
            if self._is_attribute_line(line_index, offset):
                return
            module, section, is_nfr = self._heading_at(heading_map, offset)
            attributes = self._attributes_after(line_index, offset)
            requirements.append({
                'description': req_text,
                'priority': priority or self._determine_priority(req_text),
                'category': category,
                'module': module,
                'section': section,
                'non_functional': is_nfr,
                'measure': attributes.get('measure', ''),
                'stated_category': attributes.get('category', ''),
                'stated_sub_category': attributes.get('sub-category', ''),
            })

        # Pattern 1: Explicit requirement keywords
        req_patterns = [
            r'(?:must|shall|should|will)\s+(?:be able to|allow|provide|support|enable|implement|include).*?(?:\.|$)',
            r'(?:the system|user|application|software)\s+(?:must|shall|should|will).*?(?:\.|$)',
            r'(?:requirement|req|fr)[\s\-:]+\d+.*?(?:\n|$)',
        ]

        for pattern in req_patterns:
            matches = re.finditer(pattern, text, re.IGNORECASE | re.MULTILINE)
            for match in matches:
                req_text = match.group(0).strip()
                if len(req_text) > 20:  # Filter out very short matches
                    add(req_text, match.start(), self._determine_category(req_text))

        # Pattern 2: User stories format
        user_story_pattern = r'(?:as\s+a|as\s+an)\s+.*?(?:i\s+want|i\s+need).*?(?:so\s+that)?.*?(?:\n|$)'
        matches = re.finditer(user_story_pattern, text, re.IGNORECASE | re.MULTILINE)
        for match in matches:
            req_text = match.group(0).strip()
            if len(req_text) > 20:
                add(req_text, match.start(), 'User Story', priority='Should')

        # Pattern 3: Numbered or bulleted lists that look like requirements
        for line_offset, raw_line in line_index:
            line = raw_line.strip()
            # Check if line starts with number, bullet, or dash
            if re.match(r'^(?:\d+\.|\*|\-|•)\s+', line):
                # Check if it contains requirement-like language
                if any(keyword in line.lower() for keyword in ['must', 'should', 'shall', 'will', 'enable', 'allow', 'provide', 'support']):
                    req_text = re.sub(r'^(?:\d+\.|\*|\-|•)\s+', '', line)
                    if len(req_text) > 20:
                        add(req_text, line_offset, self._determine_category(req_text))

        # Remove duplicates based on similar text, keeping the entry that carries
        # the most context (a numbered line beats a mid-sentence regex fragment)
        unique_requirements = []
        seen = {}
        for req in requirements:
            normalized = req['description'].lower()[:100]
            existing = seen.get(normalized)
            if existing is None:
                seen[normalized] = req
                unique_requirements.append(req)
            elif len(req['description']) > len(existing['description']):
                existing.update(req)

        return unique_requirements

    def _determine_priority(self, text: str) -> str:
        """
        Determine MoSCoW priority from keywords in the requirement text.

        Returns Must/Should/Could/Won't to match the MRL Priority dropdown in the
        template. Writing High/Medium/Low here produces cells that fail the
        template's own data validation.
        """
        text_lower = text.lower()
        if "won't" in text_lower or 'will not' in text_lower or 'must exclude' in text_lower \
                or 'out of scope' in text_lower or 'exclude' in text_lower:
            return "Won't"
        elif 'must' in text_lower or 'shall' in text_lower or 'critical' in text_lower \
                or 'essential' in text_lower:
            return 'Must'
        elif 'should' in text_lower or 'important' in text_lower:
            return 'Should'
        elif 'could' in text_lower or 'optional' in text_lower or 'nice to have' in text_lower:
            return 'Could'
        return 'Should'

    def _determine_category(self, text: str) -> str:
        """Determine requirement category based on content."""
        text_lower = text.lower()

        categories = {
            'Authentication': ['login', 'authentication', 'password', 'user account', 'sign in', 'sign up'],
            'Data Management': ['data', 'database', 'storage', 'save', 'retrieve', 'update', 'delete'],
            'User Interface': ['ui', 'interface', 'display', 'view', 'screen', 'button', 'form'],
            'Integration': ['integrate', 'api', 'external', 'third-party', 'interface with'],
            'Reporting': ['report', 'dashboard', 'analytics', 'metrics', 'export'],
            'Security': ['security', 'secure', 'encryption', 'authorization', 'permission', 'access control'],
            'Performance': ['performance', 'speed', 'fast', 'response time', 'scalable'],
            'Notification': ['notification', 'alert', 'email', 'notify', 'message'],
        }

        for category, keywords in categories.items():
            if any(keyword in text_lower for keyword in keywords):
                return category

        return 'General'

    def _is_redundant(self, main_category: str, sub_category: str) -> bool:
        """
        Test whether a sub-category adds nothing over its category.

        Catches exact repeats ("Performance" / "Performance"), self-restating
        padding ("General" / "General Requirements", "User Interface" /
        "Interface") and pure filler ("General Requirements" under anything).
        """
        if not sub_category:
            return True

        main_lower = main_category.strip().lower()
        sub_lower = sub_category.strip().lower()

        if main_lower == sub_lower:
            return True

        # Strip filler words and compare the meaningful remainder
        def meaningful(value: str) -> set:
            return {w for w in re.findall(r"[a-z0-9]+", value.lower())
                    if w not in self.FILLER_WORDS}

        main_words = meaningful(main_lower)
        sub_words = meaningful(sub_lower)

        # Nothing meaningful left, or the sub-category is a subset of the category
        if not sub_words:
            return True
        if sub_words and sub_words.issubset(main_words):
            return True

        return False

    def _split_category(self, req: Dict[str, str]) -> Tuple[str, str]:
        """
        Resolve CATEGORY and SUB-CATEGORY for a functional requirement.

        Preference order:
          1. Document headings - "MODULE: x" as category, section heading as sub-category
          2. Section heading as category, keyword category as sub-category
          3. Keyword category as category

        A sub-category that merely restates its category is left blank rather
        than padded with filler, so the column carries real information.
        """
        # Keyword category -> business-aligned main category
        category_mapping = {
            'Authentication': 'Security',
            'Data Management': 'Data',
            'User Interface': 'User Interface',
            'Integration': 'Integration',
            'Reporting': 'Reporting',
            'Security': 'Security',
            'Performance': 'Performance',
            'Notification': 'Communication',
            'General': 'General',
            'User Story': 'Functional',
        }

        # Accept a bare category string for backwards compatibility
        if isinstance(req, str):
            req = {'category': req}

        keyword_category = req.get('category', 'General')
        mapped = category_mapping.get(keyword_category, keyword_category)
        module = (req.get('module') or '').strip()
        section = (req.get('section') or '').strip()

        if module and section:
            main, sub = module, section
        elif module:
            main, sub = module, mapped
        elif section:
            main, sub = section, mapped
        else:
            main, sub = mapped, ''

        if self._is_redundant(main, sub):
            sub = ''

        return (main, sub)

    def _canonical_nfr_category(self, heading: str) -> Optional[str]:
        """
        Map a section heading onto a BABOK s10.30 category.

        Returns None when the heading matches nothing in the vocabulary, so the
        caller can keep the analyst's own wording and warn about it rather than
        silently filing the requirement under the wrong quality attribute.
        """
        lowered = (heading or '').lower()
        if not lowered:
            return None
        for category in self.NFR_CATEGORY_ORDER:
            for alias in self.NFR_CATEGORY_ALIASES.get(category, []):
                if alias in lowered:
                    return category
        return None

    def _split_nfr_category(self, req: Dict[str, str]) -> Tuple[str, str]:
        """
        Resolve CATEGORY and SUB-CATEGORY for a non-functional requirement.

        CATEGORY is a BABOK s10.30 quality attribute so the sheet can be read as
        a coverage checklist. SUB-CATEGORY names the part of the solution the
        threshold applies to, which is what makes two Performance requirements
        distinguishable.

        Preference order for CATEGORY:
          1. An explicit `Category:` attribute line on the requirement
          2. The section heading, mapped onto the canonical vocabulary
          3. The section heading verbatim, with a warning
          4. The keyword category, with a warning
        """
        section = (req.get('section') or '').strip()
        stated = (req.get('stated_category') or '').strip()
        sub = (req.get('stated_sub_category') or '').strip()

        main = self._canonical_nfr_category(stated) or self._canonical_nfr_category(section)
        if not main:
            main = stated or section or req.get('category', 'General')
            self.warnings.append(
                f"NFR category '{main}' is outside the BABOK s10.30 vocabulary - "
                f"rename the section heading or add a 'Category:' line "
                f"({req['description'][:60]}...)")

        # Where no sub-category was stated, the section heading can still supply
        # one if it says more than the canonical category name does
        if not sub and section and not self._is_redundant(main, section):
            sub = section

        if self._is_redundant(main, sub):
            sub = ''

        return (main, sub)

    def _sort_requirements_by_category(self, requirements: List[Dict[str, str]]) -> List[Dict[str, str]]:
        """
        Sort functional requirements by CATEGORY and then SUB-CATEGORY, so IDs are
        assigned in a logical order.
        """
        keyed = []
        for req in requirements:
            main_category, sub_category = self._split_category(req)
            keyed.append((main_category, sub_category, req))

        return [req for _, _, req in sorted(keyed, key=lambda item: (item[0], item[1]))]

    def _sort_nfrs(self, requirements: List[Dict[str, str]]) -> List[Dict[str, str]]:
        """
        Sort non-functional requirements into BABOK category order, then by
        sub-category, so the sheet reads down the s10.30 checklist.
        """
        keyed = []
        for req in requirements:
            main_category, sub_category = self._split_nfr_category(req)
            try:
                order = self.NFR_CATEGORY_ORDER.index(main_category)
            except ValueError:
                order = len(self.NFR_CATEGORY_ORDER)  # unknown categories sort last
            keyed.append((order, main_category, sub_category, req))

        return [req for _, _, _, req in
                sorted(keyed, key=lambda item: (item[0], item[1], item[2]))]

    def _check_measures(self, non_functional: List[Dict[str, str]]):
        """
        Record which non-functional requirements have no success measure.

        BABOK requires a success measure in the definition of each non-functional
        requirement; without one the requirement is not testable and the vendor
        cannot be held to it. The row is still written - a visible gap in the
        SUCCESS MEASURE column is more useful than a dropped requirement.
        """
        for req in non_functional:
            if not (req.get('measure') or '').strip():
                self.warnings.append(
                    "Non-functional requirement has no success measure and is not "
                    f"testable as written: {req['description'][:80]}")

    def _advise_on_routing(self, functional: List[Dict[str, str]]):
        """
        Flag functional requirements that read like quality thresholds.

        Advisory only. Moving them is the analyst's call, made by editing the
        source document's headings - the script never reclassifies on keywords,
        because security and integration behaviour is functional under BABOK even
        though it uses quality-attribute vocabulary.
        """
        for req in functional:
            text = req['description'].lower()
            if any(signal in text for signal in self.NFR_SIGNALS):
                self.advisories.append(
                    "Reads as a quality threshold - consider moving under "
                    f"MODULE: NON-FUNCTIONAL with a success measure: "
                    f"{req['description'][:80]}")

    def read_text_file(self, file_path: str) -> str:
        """Read content from a text file."""
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                return f.read()
        except UnicodeDecodeError:
            # Try with different encoding if UTF-8 fails
            with open(file_path, 'r', encoding='latin-1') as f:
                return f.read()

    def populate_excel(self, requirements: List[Dict[str, str]],
                      project_name: str = "Project",
                      source_file: str = "") -> str:
        """
        Write the extracted requirements into a new workbook, functional
        requirements on one sheet and non-functional on the other.
        Returns the path to the created file.
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_filename = f"FRS_{project_name}_{timestamp}.xlsx"
        output_path = self.output_dir / output_filename

        # Build the workbook from scratch - no template file to copy, so there are
        # no placeholder rows to clear and no external links to repair
        wb = create_workbook(project_name)

        functional = [r for r in requirements if not r.get('non_functional')]
        non_functional = [r for r in requirements if r.get('non_functional')]

        self._write_functional(wb[FUNCTIONAL_SHEET['title']], functional)
        self._write_non_functional(wb[NON_FUNCTIONAL_SHEET['title']], non_functional)

        wb.save(output_path)
        return str(output_path)

    def _write_functional(self, ws, requirements: List[Dict[str, str]]):
        """CATEGORY, SUB-CATEGORY, ID, DESCRIPTION and MRL Priority; the vendor
        completes COMPLIANCE and COMMENTS."""
        columns = FUNCTIONAL_SHEET['columns']
        start_row = FUNCTIONAL_SHEET['first_data_row']

        for idx, req in enumerate(self._sort_requirements_by_category(requirements),
                                  start=1):
            row = start_row + idx - 1
            main_category, sub_category = self._split_category(req)
            values = {
                'CATEGORY': main_category,
                'SUB-CATEGORY': sub_category,
                'ID': f"FR-{idx:03d}",
                'DESCRIPTION': req['description'],
                'MRL Priority': req['priority'],
            }
            for name, value in values.items():
                ws.cell(row=row, column=columns.index(name) + 1, value=value)
            style_requirement_row(ws, row, FUNCTIONAL_SHEET)

        self._extend_data_validations(ws, start_row,
                                     start_row + len(requirements) - 1)

    def _write_non_functional(self, ws, requirements: List[Dict[str, str]]):
        """As the functional sheet, plus the SUCCESS MEASURE that makes each
        quality attribute testable."""
        columns = NON_FUNCTIONAL_SHEET['columns']
        start_row = NON_FUNCTIONAL_SHEET['first_data_row']

        self._check_measures(requirements)

        for idx, req in enumerate(self._sort_nfrs(requirements), start=1):
            row = start_row + idx - 1
            main_category, sub_category = self._split_nfr_category(req)
            values = {
                'CATEGORY': main_category,
                'SUB-CATEGORY': sub_category,
                'ID': f"NFR-{idx:03d}",
                'DESCRIPTION': req['description'],
                'SUCCESS MEASURE': req.get('measure', ''),
                'MRL Priority': req['priority'],
            }
            for name, value in values.items():
                ws.cell(row=row, column=columns.index(name) + 1, value=value)
            style_requirement_row(ws, row, NON_FUNCTIONAL_SHEET)

        self._extend_data_validations(ws, start_row,
                                     start_row + len(requirements) - 1)

    def _extend_data_validations(self, ws, first_row: int, last_row: int):
        """
        Stretch the MRL Priority and COMPLIANCE dropdowns over every data row.

        create_workbook() attaches each validation to the first data row only,
        since the requirement count is not known until the rows have been written.
        """
        if last_row < first_row:
            return

        for dv in ws.data_validations.dataValidation:
            extended = []
            for rng in dv.sqref.ranges:
                letter = get_column_letter(rng.min_col)
                extended.append(f"{letter}{first_row}:{letter}{last_row}")
            dv.sqref = ' '.join(extended)

    def process_file(self, input_file: str, project_name: str = None) -> str:
        """
        Main method to process a text file and generate the requirements workbook.

        Args:
            input_file: Path to the text file containing requirements
            project_name: Name of the project (defaults to filename)

        Returns:
            Path to the generated Excel file
        """
        input_path = Path(input_file)

        if not input_path.exists():
            raise FileNotFoundError(f"Input file not found: {input_file}")

        # Determine project name
        if project_name is None:
            project_name = input_path.stem

        # Read and extract requirements
        print(f"Reading file: {input_file}")
        text_content = self.read_text_file(input_file)

        print("Extracting requirements...")
        requirements = self.extract_requirements_from_text(text_content)

        functional = [r for r in requirements if not r.get('non_functional')]
        non_functional = [r for r in requirements if r.get('non_functional')]
        self._advise_on_routing(functional)

        print(f"Found {len(functional)} functional and "
              f"{len(non_functional)} non-functional requirements")

        if len(requirements) == 0:
            print("Warning: No requirements found. The file may not contain requirement-like statements.")
            print("Tip: Requirements should contain keywords like 'must', 'should', 'shall', 'will', etc.")
        if len(non_functional) == 0:
            print("Warning: No non-functional requirements found. The"
                  " Non-Functional Requirements sheet will be empty.")
            print("Tip: put them under 'MODULE: NON-FUNCTIONAL' with one section"
                  " per BABOK category, and give each a 'Measure:' line.")

        # Populate Excel
        print("Generating Excel file...")
        output_path = self.populate_excel(requirements, project_name, str(input_path))

        self._report()

        print(f"Successfully created: {output_path}")
        return output_path

    def _report(self):
        """Print the quality warnings and routing advisories gathered en route."""
        # Warnings can repeat where several requirements share a bad heading
        for warning in dict.fromkeys(self.warnings):
            print(f"  WARNING: {warning}")
        for advisory in dict.fromkeys(self.advisories):
            print(f"  REVIEW: {advisory}")


def main():
    """Command-line interface for the script."""
    if len(sys.argv) < 2:
        print("Usage: python functional_requirement.py <input_text_file> [project_name]")
        print("\nExample:")
        print("  python functional_requirement.py requirements.txt MyProject")
        sys.exit(1)

    input_file = sys.argv[1]
    project_name = sys.argv[2] if len(sys.argv) > 2 else None

    try:
        extractor = FunctionalRequirementExtractor()
        output_file = extractor.process_file(input_file, project_name)
        print(f"\nRequirements extracted successfully!")
        print(f"Output: {output_file}")
    except Exception as e:
        # Show the traceback - a bare message hides where generation failed
        import traceback
        traceback.print_exc()
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
